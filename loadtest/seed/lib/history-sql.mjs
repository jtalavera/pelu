// Set-based T-SQL that bulk-generates one tenant's history (docs/staging-env.md T6): clients,
// past appointments, fichas (service records), invoices on a separate INACTIVE "historic" fiscal
// stamp, payments, tips, cash sessions/movements, and upcoming appointments for the agenda.
//
// Deterministic by construction: every random choice is ABS(CHECKSUM(seed, tenantIndex, …)) %
// m, keyed by the tenant's INDEX (not its identity id), so tenant k always gets the same shape
// and a --tenants=30 DB is the --tenants=20 DB plus one more block.
//
// Dates are relative to an anchor date (stored in loadtest_meta). up.sh shifts them by whole
// weeks on import, so an old golden BACPAC still has "today" and an upcoming agenda.
//
// The catalog (services, professionals, schedules, fiscal stamp, SIFEN material) is created
// through the real API first, so it is valid by construction; only volume goes in by SQL.

const FIRST = ["Ana", "María", "Lucía", "Sofía", "Valeria", "Camila", "Laura", "Paula", "Carla", "Julia",
  "Andrea", "Rocío", "Natalia", "Gabriela", "Silvia", "Patricia", "Mónica", "Diana", "Elena", "Rosa"];
const LAST = ["González", "Benítez", "Martínez", "López", "Giménez", "Vera", "Duarte", "Ramírez", "Ortiz", "Rojas",
  "Báez", "Cáceres", "Fernández", "Acosta", "Villalba", "Sosa", "Núñez", "Ayala", "Torres", "Franco"];

const q = (s) => `N'${String(s).replace(/'/g, "''")}'`;
const valuesList = (arr) => arr.map((v, i) => `(${i}, ${q(v)})`).join(",\n  ");

function mixCase(mix, salt) {
  // CASE over cumulative percentages, e.g. {COMPLETED:85, CANCELLED:8, NO_SHOW:7}.
  let acc = 0;
  const parts = Object.entries(mix).map(([k, pct]) => {
    acc += pct;
    return `WHEN ABS(CHECKSUM(@seed, @tix, a.d, a.p, a.s, ${salt})) % 100 < ${acc} THEN '${k}'`;
  });
  return `CASE ${parts.join(" ")} ELSE '${Object.keys(mix).at(-1)}' END`;
}

/**
 * @param {object} t   { id, index, adminUserId }
 * @param {object[]} professionals  [{ id }]
 * @param {object[]} services       [{ id, name, price, duration }]
 * @param {object} v   volumes.json
 * @param {string} anchorDate       YYYY-MM-DD
 */
export function historySql(t, professionals, services, v, anchorDate) {
  const p = v.perTenant;
  const profValues = professionals.map((x, i) => `(${i}, ${x.id})`).join(", ");
  const svcValues = services
    .map((s, i) => `(${i}, ${s.id}, ${q(s.name)}, ${Number(s.price)}, ${Number(s.duration)})`)
    .join(",\n  ");
  const workingDays = v.workingDays.join(", ");
  const slotHours = (count) =>
    Array.from({ length: count }, (_, s) => `(${s}, ${v.openingHour + Math.floor((s * (v.closingHour - v.openingHour)) / count)})`).join(", ");

  return `-- Generated by loadtest/seed/seed.mjs — tenant index ${t.index}, id ${t.id}. Do not edit.
SET NOCOUNT ON;
SET XACT_ABORT ON;
BEGIN TRANSACTION;

DECLARE @tenant BIGINT = ${t.id}, @tix INT = ${t.index}, @seed INT = ${v.seed}, @admin BIGINT = ${t.adminUserId};
DECLARE @anchor DATE = '${anchorDate}';
DECLARE @utcShift INT = ${-v.utcOffsetHours};  -- UTC = local + @utcShift hours
DECLARE @clients INT = ${p.clients};

IF EXISTS (SELECT 1 FROM clients WHERE tenant_id = @tenant AND email LIKE N'lt-t%@loadtest.invalid')
  THROW 50010, 'loadtest history already generated for this tenant', 1;

SELECT TOP (20000) ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) AS n INTO #n
FROM sys.all_objects a CROSS JOIN sys.all_objects b;

CREATE TABLE #fn (ix INT PRIMARY KEY, v NVARCHAR(40));
INSERT INTO #fn VALUES
  ${valuesList(FIRST)};
CREATE TABLE #ln (ix INT PRIMARY KEY, v NVARCHAR(40));
INSERT INTO #ln VALUES
  ${valuesList(LAST)};
CREATE TABLE #prof (ix INT PRIMARY KEY, id BIGINT NOT NULL);
INSERT INTO #prof VALUES ${profValues};
CREATE TABLE #svc (ix INT PRIMARY KEY, id BIGINT NOT NULL, name NVARCHAR(255), price DECIMAL(19,2), dur INT);
INSERT INTO #svc VALUES
  ${svcValues};
DECLARE @nprof INT = (SELECT COUNT(*) FROM #prof), @nsvc INT = (SELECT COUNT(*) FROM #svc);

-- ── Clients ────────────────────────────────────────────────────────────────────────────────
INSERT INTO clients (tenant_id, full_name, phone, email, active, is_generic, visit_count, created_at)
SELECT @tenant,
       CONCAT(f.v, N' ', l.v, N' ', n.n),
       N'0000000000',
       CONCAT(N'lt-t', @tix, N'-c', n.n, N'@loadtest.invalid'),
       1, 0, 0,
       DATEADD(DAY, -${v.historyDays + 30} + (n.n % 30), CAST(@anchor AS DATETIME2))
FROM #n n
JOIN #fn f ON f.ix = (n.n * 7 + @tix) % ${FIRST.length}
JOIN #ln l ON l.ix = (n.n * 13 + @tix * 3) % ${LAST.length}
WHERE n.n <= @clients;

CREATE TABLE #cli (ix INT PRIMARY KEY, id BIGINT NOT NULL, name NVARCHAR(255));
INSERT INTO #cli
SELECT CAST(REPLACE(REPLACE(email, CONCAT(N'lt-t', @tix, N'-c'), N''), N'@loadtest.invalid', N'') AS INT), id, full_name
FROM clients WHERE tenant_id = @tenant AND email LIKE CONCAT(N'lt-t', @tix, N'-c%@loadtest.invalid');

-- ── Working days (Monday = 1; 1900-01-01 was a Monday, so this ignores @@DATEFIRST) ────────
CREATE TABLE #day (d INT PRIMARY KEY, dt DATE NOT NULL, past BIT NOT NULL);
INSERT INTO #day
SELECT x.d, x.dt, CASE WHEN x.d > 0 THEN 1 ELSE 0 END
FROM (
  SELECT n.n AS d, DATEADD(DAY, -n.n, @anchor) AS dt FROM #n n WHERE n.n <= ${v.historyDays}
  UNION ALL
  SELECT 1 - n.n, DATEADD(DAY, n.n - 1, @anchor) FROM #n n WHERE n.n <= ${v.futureDays}
) x
WHERE (DATEDIFF(DAY, '19000101', x.dt) % 7) + 1 IN (${workingDays});

-- ── Cash sessions: one per past working day, opened at opening hour, closed at closing hour ─
CREATE TABLE #sess (dt DATE PRIMARY KEY, id BIGINT NOT NULL, opened_at DATETIME2 NOT NULL);
MERGE cash_sessions AS tgt
USING (SELECT dt, DATEADD(HOUR, ${v.openingHour} + @utcShift, CAST(dt AS DATETIME2)) AS opened_at,
              DATEADD(HOUR, ${v.closingHour} + @utcShift, CAST(dt AS DATETIME2)) AS closed_at
       FROM #day WHERE past = 1) AS src
ON 1 = 0
WHEN NOT MATCHED THEN
  INSERT (tenant_id, opened_by_user_id, opened_at, opening_cash_amount, closed_at, closed_by_user_id, counted_cash_amount)
  VALUES (@tenant, @admin, src.opened_at, ${p.openingCashAmount}, src.closed_at, @admin, ${p.openingCashAmount})
OUTPUT src.dt, inserted.id, src.opened_at INTO #sess (dt, id, opened_at);

INSERT INTO cash_movements (tenant_id, cash_session_id, type, amount, after_close, created_by_user_id, created_at)
SELECT @tenant, s.id, CASE WHEN n.n % 2 = 1 THEN 'MANUAL_IN' ELSE 'MANUAL_OUT' END,
       10000 + (ABS(CHECKSUM(@seed, @tix, DATEDIFF(DAY, '19000101', s.dt), n.n, 9)) % 5) * 10000,
       0, @admin, DATEADD(HOUR, 1 + n.n, s.opened_at)
FROM #sess s JOIN #n n ON n.n <= ${p.cashMovementsPerSession};

-- ── Appointments (past: every slot of every professional; future: fewer slots, CONFIRMED) ──
CREATE TABLE #slotPast (s INT PRIMARY KEY, h INT NOT NULL);
INSERT INTO #slotPast VALUES ${slotHours(p.appointmentsPerProfessionalPerDay)};
CREATE TABLE #slotFuture (s INT PRIMARY KEY, h INT NOT NULL);
INSERT INTO #slotFuture VALUES ${slotHours(p.futureAppointmentsPerProfessionalPerDay)};

CREATE TABLE #appt (
  k INT IDENTITY(1,1) PRIMARY KEY, d INT, p INT, s INT, dt DATE, past BIT,
  client_id BIGINT, client_name NVARCHAR(255), prof_id BIGINT, svc_id BIGINT, svc_name NVARCHAR(255),
  price DECIMAL(19,2), start_at DATETIME2, end_at DATETIME2, status NVARCHAR(32), tip DECIMAL(19,2)
);
INSERT INTO #appt (d, p, s, dt, past, prof_id, start_at)
SELECT dy.d, pr.ix, sl.s, dy.dt, 1, pr.id, DATEADD(HOUR, sl.h + @utcShift, CAST(dy.dt AS DATETIME2))
FROM #day dy CROSS JOIN #prof pr CROSS JOIN #slotPast sl WHERE dy.past = 1;
INSERT INTO #appt (d, p, s, dt, past, prof_id, start_at)
SELECT dy.d, pr.ix, sl.s, dy.dt, 0, pr.id, DATEADD(HOUR, sl.h + @utcShift, CAST(dy.dt AS DATETIME2))
FROM #day dy CROSS JOIN #prof pr CROSS JOIN #slotFuture sl WHERE dy.past = 0;

UPDATE a SET
  svc_id = sv.id, svc_name = sv.name, price = sv.price,
  end_at = DATEADD(MINUTE, sv.dur, a.start_at),
  client_id = c.id, client_name = c.name,
  status = CASE WHEN a.past = 0 THEN 'CONFIRMED' ELSE ${mixCase(p.statusMix, 3)} END,
  tip = CASE WHEN ABS(CHECKSUM(@seed, @tix, a.d, a.p, a.s, 4)) % 100 < ${p.tipPercentOfInvoices} THEN ${p.tipAmount} ELSE 0 END
FROM #appt a
JOIN #svc sv ON sv.ix = ABS(CHECKSUM(@seed, @tix, a.d, a.p, a.s, 1)) % @nsvc
JOIN #cli c ON c.ix = 1 + ABS(CHECKSUM(@seed, @tix, a.d, a.p, a.s, 2)) % @clients;

CREATE TABLE #amap (k INT PRIMARY KEY, id BIGINT NOT NULL);
MERGE appointments AS tgt
USING #appt AS src ON 1 = 0
WHEN NOT MATCHED THEN
  INSERT (tenant_id, client_id, professional_id, service_id, start_at, end_at, status, cancel_reason)
  VALUES (@tenant, src.client_id, src.prof_id, src.svc_id, src.start_at, src.end_at, src.status,
          CASE WHEN src.status = 'CANCELLED' THEN N'loadtest' END)
OUTPUT src.k, inserted.id INTO #amap (k, id);

-- ── Fichas (service records) for every completed appointment ───────────────────────────────
CREATE TABLE #srmap (k INT PRIMARY KEY, id BIGINT NOT NULL);
MERGE service_records AS tgt
USING (SELECT a.*, m.id AS appt_id FROM #appt a JOIN #amap m ON m.k = a.k WHERE a.status = 'COMPLETED') AS src
ON 1 = 0
WHEN NOT MATCHED THEN
  INSERT (tenant_id, client_id, status, total_amount, created_at, closed_at, appointment_id)
  VALUES (@tenant, src.client_id, 'CLOSED', src.price, src.start_at, src.end_at, src.appt_id)
OUTPUT src.k, inserted.id INTO #srmap (k, id);

UPDATE ap SET service_record_id = sr.id
FROM appointments ap JOIN #amap m ON m.id = ap.id JOIN #srmap sr ON sr.k = m.k;

INSERT INTO service_record_lines (service_record_id, service_id, professional_id, description, unit_price, quantity)
SELECT sr.id, a.svc_id, a.prof_id, a.svc_name, a.price, 1
FROM #appt a JOIN #srmap sr ON sr.k = a.k;

INSERT INTO service_record_tips (service_record_id, professional_id, amount)
SELECT sr.id, a.prof_id, a.tip FROM #appt a JOIN #srmap sr ON sr.k = a.k WHERE a.tip > 0;

-- ── Invoices on an INACTIVE historic stamp (the active stamp stays empty: up.sh rebases it) ─
DECLARE @invoices INT = (SELECT COUNT(*) FROM #srmap);
INSERT INTO fiscal_stamps (tenant_id, stamp_number, valid_from, valid_until, range_from, range_to,
                           next_emission_number, active, locked_after_invoice, establishment, expedition_point)
VALUES (@tenant, CONCAT(N'LTHIST', @tix), DATEADD(DAY, -${v.historyDays + 1}, @anchor), DATEADD(DAY, -1, @anchor),
        1, 9999999, @invoices + 1, 0, 1, 1, 1);
DECLARE @histStamp BIGINT = SCOPE_IDENTITY();
DECLARE @ruc NVARCHAR(32) = (SELECT TOP 1 ruc FROM business_profiles WHERE tenant_id = @tenant);

CREATE TABLE #imap (k INT PRIMARY KEY, id BIGINT NOT NULL);
MERGE invoices AS tgt
USING (SELECT a.*, sr.id AS sr_id, m.id AS appt_id, s.id AS sess_id,
              ROW_NUMBER() OVER (ORDER BY a.start_at, a.k) AS num
       FROM #appt a JOIN #srmap sr ON sr.k = a.k JOIN #amap m ON m.k = a.k JOIN #sess s ON s.dt = a.dt) AS src
ON 1 = 0
WHEN NOT MATCHED THEN
  INSERT (tenant_id, fiscal_stamp_id, invoice_number, client_id, client_display_name, business_ruc, status,
          subtotal, total, issued_at, cash_session_id, tips_amount, service_record_id, appointment_id)
  VALUES (@tenant, @histStamp, src.num, src.client_id, src.client_name, @ruc, 'ISSUED',
          src.price, src.price, src.end_at, src.sess_id, src.tip, src.sr_id, src.appt_id)
OUTPUT src.k, inserted.id INTO #imap (k, id);

INSERT INTO invoice_lines (invoice_id, service_id, professional_id, description, quantity, unit_price, line_total)
SELECT i.id, a.svc_id, a.prof_id, a.svc_name, 1, a.price, a.price FROM #appt a JOIN #imap i ON i.k = a.k;

INSERT INTO invoice_payment_allocations (invoice_id, method, amount)
SELECT i.id, ${(() => {
    let acc = 0;
    const parts = Object.entries(p.paymentMix).map(([k, pct]) => {
      acc += pct;
      return `WHEN ABS(CHECKSUM(@seed, @tix, a.d, a.p, a.s, 5)) % 100 < ${acc} THEN '${k}'`;
    });
    return `CASE ${parts.join(" ")} ELSE 'CASH' END`;
  })()}, a.price + a.tip
FROM #appt a JOIN #imap i ON i.k = a.k;

INSERT INTO invoice_tips (invoice_id, professional_id, amount)
SELECT i.id, a.prof_id, a.tip FROM #appt a JOIN #imap i ON i.k = a.k WHERE a.tip > 0;

UPDATE c SET visit_count = x.visits
FROM clients c JOIN (SELECT client_id, COUNT(*) AS visits FROM #appt WHERE status = 'COMPLETED' GROUP BY client_id) x
  ON x.client_id = c.id;

COMMIT TRANSACTION;
PRINT CONCAT('loadtest history: tenant ', @tenant, ' clients=', @clients, ' appointments=',
             (SELECT COUNT(*) FROM #appt), ' invoices=', @invoices);
`;
}
